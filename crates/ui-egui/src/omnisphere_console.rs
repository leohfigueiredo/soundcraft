#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_control_is_unique_and_in_range() {
        let mut ids = std::collections::HashSet::new();
        let mut ccs = std::collections::HashSet::new();
        for spec in SPECS.iter().chain(HEADER.iter()) {
            assert!(ids.insert(spec.id), "duplicate id {}", spec.id);
            assert!(ccs.insert(spec.cc), "CC {} used twice ({})", spec.cc, spec.id);
            assert!(!spec.automation.is_empty() && spec.min < spec.max, "{} is malformed", spec.id);
            assert!(spec.default >= spec.min && spec.default <= spec.max, "{} default outside its range", spec.id);
            assert!(spec.group == 255 || (spec.group as usize) < RACKS.len(), "{} has no rack", spec.id);
        }
        for s in SELECTS {
            assert!(ids.insert(s.id), "duplicate id {}", s.id);
            assert!(ccs.insert(s.cc), "CC {} used twice ({})", s.cc, s.id);
            assert!((s.group as usize) < RACKS.len(), "{} has no rack", s.id);
        }
    }

    #[test]
    fn every_rack_and_bank_has_content() {
        for (index, rack) in RACKS.iter().enumerate() {
            assert!(SPECS.iter().any(|s| s.group as usize == index) || SELECTS.iter().any(|s| s.group as usize == index), "rack `{rack}` is empty");
        }
        for (index, category) in CATEGORIES.iter().enumerate() {
            assert!(MODELS.iter().any(|m| m.category == index), "bank `{}` is empty", category.title);
        }
    }
}
