//!
//! Same contract as every console: [`SPECS`]/[`SELECTS`] is the map (id, range, unit, MIDI CC,
//! plugin parameter name), every change leaves through `console_kit::dispatch`/`select`, and the
//! instrument's own [`PALETTE`] tints the window so it reads as this instrument.

